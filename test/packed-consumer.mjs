import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, stat, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { build } from "vite";

const workspace = await mkdtemp("/private/tmp/osx-packed-consumer-");
const sourceManifest = JSON.parse(await readFile(new URL("../package.json", import.meta.url), "utf8"));
const packageName = sourceManifest.name;
const packageDirectory = join(workspace, "node_modules", ...packageName.split("/"));
const packOutput = JSON.parse(execFileSync("npm", ["pack", "--json", "--pack-destination", workspace], { encoding: "utf8" }));
const archive = join(workspace, packOutput[0].filename);
await writeFile(join(workspace, "package.json"), JSON.stringify({ private: true, type: "module", dependencies: { [packageName]: `file:${archive}` } }));
execFileSync("npm", ["install", "--ignore-scripts", "--no-package-lock", "--prefer-offline"], { cwd: workspace, stdio: "pipe" });
await writeFile(join(workspace, "index.html"), '<!doctype html><html><body><div id="app"></div><script type="module" src="/main.js"></script></body></html>');
await writeFile(join(workspace, "main.js"), `import { registerOsxComponents } from ${JSON.stringify(packageName)}; import ${JSON.stringify(`${packageName}/theme.css`)}; registerOsxComponents(); document.querySelector("#app").innerHTML = "<osx-alert title=Ready></osx-alert>";`);
const result = await build({ root: workspace, configFile: false, logLevel: "silent", build: { write: false } });
const outputs = Array.isArray(result) ? result.flatMap((item) => item.output) : result.output;
const code = outputs.filter((item) => item.type === "chunk").map((item) => item.code).join("\n");
assert.match(code, /customElements/, "packed consumer bundle did not include registration runtime");
const manifest = JSON.parse(await readFile(join(packageDirectory, "package.json"), "utf8"));
assert.equal(manifest.version, sourceManifest.version);
const packagedSkill = join(packageDirectory, "skills/build-with-osx-components/SKILL.md");
assert.ok((await stat(packagedSkill)).isFile(), "packed artifact did not include the agent skill");
const agentTarget = join(workspace, "agent-target");
execFileSync(process.execPath, [join(packageDirectory, "bin/osx-components.mjs"), "agent", "install", "--target", "agents", "--cwd", agentTarget], { stdio: "pipe" });
assert.ok((await stat(join(agentTarget, ".agents/skills/build-with-osx-components/SKILL.md"))).isFile(), "packed installer did not install the agent skill");
process.stdout.write("✓ packed npm artifact installed and bundled\n");
